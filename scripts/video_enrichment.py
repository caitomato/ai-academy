def enrich(lesson):
    for lid, heading, note, prompt, walkthrough, checks, failure in CARDS:
        if lesson['id'] != lid:
            continue
        # The case and misconception already have dedicated sections in the UI.
        # Keep explanation distinct instead of repeating the same paragraph.
        lesson['sections'] = [lesson['sections'][0], dict(title=heading, text=note)]
        lesson['lab'] = dict(
            title=heading,
            setup='使用自己的空练习目录和虚构数据。没有相应工具时，可以先在笔记里完成任务单与验收方案。',
            prompt=prompt,
            walkthrough=[dict(action=a, expected=b) for a,b in walkthrough],
            checks=checks,
            troubleshooting=[dict(symptom=failure[0], remedy=failure[1])],
        )
        lesson['minutes'] = max(lesson['minutes'], 18)
        lesson['sourceNote'] = '主题综合本地学习资料与补充视频文稿；实操、说明与题目为原创编写。安装、功能与计费以当前官方文档为准。'
        # A concrete failure scenario replaces a rote recall item, retaining its ID.
        q = lesson['test'][3]
        q.update(prompt=failure[0], options=[failure[1], '无需核对实际结果，直接按完成处理。', '重复全部操作直到不再报错，不记录原因。'], answer=[failure[1]], explanation=failure[1]+' 本题考查如何根据观察结果定位问题并保护已有成果。', hint='先定位失败发生在哪个环节，再做有范围的修正。')
        if lid in SCENARIOS:
            situation, choices, reasoning = SCENARIOS[lid]
            q.update(prompt=situation, options=choices[:], answer=[choices[0]], explanation=reasoning, hint='先区分已知证据、缺失项与允许执行的范围。')
        # Rotate choices without changing answers or progress identity.
        off = sum(ord(c) for c in lid) % 3
        q['options'] = q['options'][off:] + q['options'][:off]
        apply_operations(lesson)
        break
