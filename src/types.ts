export type Question = {
  id: string;
  lessonId: string;
  type: "single" | "multiple" | "boolean" | "fill" | "code" | "order" | "prediction" | "troubleshoot" | "scenario";
  optionExplanations?: Record<string, string>;
  prompt: string;
  options: string[];
  answer: string[];
  explanation: string;
  hint: string;
  code?: string;
};
export type Lesson = {
  id: string;
  chapterId: number;
  title: string;
  pages: string;
  minutes: number;
  objectives: string[];
  sections: { title: string; text: string }[];
  example: string;
  task: string;
  steps: string[];
  terms: string[];
  misconception: string;
  code?: string;
  questions: Question[];
  test: Question[];
  sourceNote?: string;
  subtitle?: string;
  introduction?: string;
  summary?: string;
  prerequisites?: string[];
  developmentStatus?: "reviewed" | "needs-expansion";
  analogy?: string;
  decisionLab?: { title: string; introduction: string; stages: { title: string; context: string; options: { label: string; result: string; correct: boolean }[] }[] };
  references?: { title: string; href: string }[];
  experience?: {
    kind: "node-project";
    projectName: string;
    files: { name: string; description: string; content?: string }[];
    fields: { name: string; explanation: string; content: string }[];
    walkthrough: { title: string; action: string; command: string; expected: string; reason: string; recovery: string }[];
    troubleshooting: { symptom: string; diagnosis: string; resolution: string }[];
  };
  lab?: {
    title: string;
    setup: string;
    prompt: string;
    walkthrough: { action: string; expected: string; code?: string }[];
    checks: string[];
    troubleshooting: { symptom: string; remedy: string }[];
    resources?: { title: string; href: string; download?: boolean }[];
  };
};
export type Chapter = {
  id: number;
  title: string;
  description: string;
  lessons: Lesson[];
};
export type Attempt = {
  id: string;
  questionId: string;
  answer: string[];
  correct: boolean;
  date: string;
};
export type State = {
  version: 1;
  completed: string[];
  bookmarks: string[];
  recent: string[];
  attempts: Attempt[];
  resolved: string[];
  scores: Record<string, number>;
  exams: { chapterId: number; score: number; date: string }[];
  days: string[];
  notes: Record<string, string>;
  taskDays: string[];
  tasks: string[];
  studySeconds?: Record<string, number>;
};
